"""Names pages: curated lists with origin and meaning. Static articles (no popularity data yet)."""
from sp import article_page


def _names_body(lang, intro, rows, choose_title, tips):
    """rows: list of (name, origin, meaning). tips: list of 3 strings."""
    head = {"en": ("Name", "Origin", "Meaning"), "fr": ("Prénom", "Origine", "Signification")}[lang]
    note = {"en": "Meanings follow standard etymological dictionaries of given names; where scholars disagree, we say so. Popularity varies a great deal by country and by decade.",
            "fr": "Les significations suivent les dictionnaires étymologiques de référence des prénoms ; quand les spécialistes ne s'accordent pas, nous le disons. La popularité varie beaucoup selon le pays et la décennie."}[lang]
    th = "".join(f"<th>{h}</th>" for h in head)
    tr = "".join(f"<tr><td><strong>{n}</strong></td><td>{o}</td><td>{m}</td></tr>" for n, o, m in rows)
    li = "".join(f"<li>{t}</li>" for t in tips)
    return f"""
<p>{intro}</p>
<table><thead><tr>{th}</tr></thead><tbody>{tr}</tbody></table>
<h2>{choose_title}</h2>
<ul>{li}</ul>
<p class="small">{note}</p>
"""


def _page(slug, title, desc, intro, rows_en, rows_fr, tips_en, tips_fr):
    article_page("names", slug, title, desc, {
        "en": _names_body("en", intro["en"], rows_en, "How to choose", tips_en),
        "fr": _names_body("fr", intro["fr"], rows_fr, "Comment choisir", tips_fr),
    })


